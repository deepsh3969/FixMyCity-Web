/* Generates dist/ from the source files, injecting runtime config
   from environment variables. Never writes secrets into source. */

const fs = require("fs");
const path = require("path");

const root = __dirname;
const dist = path.join(root, "dist");

function loadDotEnv() {
    const envPath = path.join(root, ".env");

    if (!fs.existsSync(envPath)) {
        return;
    }

    const lines = fs.readFileSync(envPath, "utf8").split(/\r?\n/);

    for (const line of lines) {
        const match = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);

        if (!match) {
            continue;
        }

        const key = match[1];
        let value = match[2];

        value = value.replace(/^["']|["']$/g, "");

        if (!(key in process.env)) {
            process.env[key] = value;
        }
    }
}

loadDotEnv();

const mapsKey = (process.env.GOOGLE_MAPS_API_KEY || "").trim();

fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });

for (const file of ["index.html", "script.js", "style.css", "favicon.svg"]) {
    fs.copyFileSync(path.join(root, file), path.join(dist, file));
}

const htmlPath = path.join(dist, "index.html");
let html = fs.readFileSync(htmlPath, "utf8");

const configTag = '<script src="config.js"></script>';

if (!html.includes(configTag)) {
    html = html.replace(
        '<script src="script.js"></script>',
        configTag + '\n<script src="script.js"></script>'
    );
}

fs.writeFileSync(htmlPath, html, "utf8");

const config =
    "/* Generated by build.js - do not edit, do not commit. */\n" +
    "window.APP_CONFIG = " +
    JSON.stringify({ GOOGLE_MAPS_API_KEY: mapsKey }, null, 2) +
    ";\n";

fs.writeFileSync(path.join(dist, "config.js"), config, "utf8");

console.log(
    "Build complete: dist/ (Google Maps API key: " +
        (mapsKey ? "loaded from environment" : "NOT SET") +
        ")"
);
